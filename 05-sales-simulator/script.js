const {root,action,reward} = Game;
let customer,index,trust,interest,records,reply,hint,finished;
const clamp = value=>Math.min(100,Math.max(0,value));

function restart() {
  customer=null;
  index=0;
  trust=40;
  interest=35;
  records=[];
  reply=null;
  hint=false;
  finished=false;
  render();
}

function avatar(person, classes='avatar') {
  return `<img class="${classes}" src="../assets/images/buyer-${cases.indexOf(person)+1}.webp" alt="" width="320" height="320">`;
}

function stage() {
  return index===2 && records[1]?.trust<56 ? customer.repair : customer.stages[index];
}

function rate() {
  return Math.round(trust*.55+interest*.45);
}

function render() {
  if (!customer) {
    root.innerHTML = `<div class="sales-intro"><h2>Выберите покупателя</h2><p>У каждого пять решений в диалоге. Ответы влияют на доверие, интерес и готовность к просмотру.</p></div><div class="persona-grid">${cases.map((person,i)=>`<article class="persona">${avatar(person,'persona-photo')}<div><h3>${person.name}</h3><p class="persona-type">${person.type}</p><p>${person.need}</p>${action('Начать диалог','customer',i)}</div></article>`).join('')}</div>`;
    return;
  }
  const score = records.reduce((sum,record)=>sum+record.points,0);
  if (finished) {
    const weak = [...new Set(records.filter(record=>!record.good).map(record=>record.topic))];
    root.innerHTML = reward({title:rate()>=70?'Покупатель готов к просмотру':rate()>=48?'Покупатель берёт паузу':'Покупатель пока не готов',score:score+50,
      badge:score>=80?'Мастер показа':'Диалог завершён',detail:`${customer.name} · готовность к просмотру ${rate()}%. Удачных решений: ${records.filter(record=>record.good).length} из 5.`,
      extra:`<div class="debrief"><h3>Разбор диалога</h3><ol>${records.map(record=>`<li><strong>${record.good?'Удачный ответ':'Что улучшить'} · ${record.topic}</strong><p>Ваш ответ: «${record.answer}».</p><p>${record.feedback}</p></li>`).join('')}</ol><p><strong>Повторить:</strong> ${weak.length?weak.join(', '):'планировки, двор и маршрут от лобби до площадок'}.</p></div>`});
    return;
  }

  const [question,good,bad,topic,tip] = reply ? reply.stage : stage();
  const options = index%2 ? [bad,good] : [good,bad];
  const meter=(label,value)=>`<div><div class="stats"><span>${label}</span><span>${value}%</span></div><progress class="meter" max="100" value="${value}" aria-label="${label}"></progress></div>`;
  root.innerHTML = `<div class="sales-layout"><aside class="panel sales-profile stack"><div class="sales-person">${avatar(customer)}<div><h2>${customer.name}</h2><p>${customer.type}</p></div></div><p>${customer.need}</p>${meter('Доверие',trust)}${meter('Интерес',interest)}${meter('Готовность к просмотру',rate())}<p class="score" role="status">${score} баллов ${reply?.points?`<span class="gain">+${reply.points}</span>`:''}</p></aside><section class="panel chat stack"><div class="chat-head"><h2>Диалог с покупателем</h2><span>Решение ${index+1} / 5</span></div>${index===2 && question===customer.repair[0]?'<p class="chat-note">Покупатель возвращается к своему главному сомнению.</p>':''}
    <div class="message appear">${avatar(customer)}<p>${question}</p></div>
    ${reply ? `<div class="message message-out appear"><p>${reply.answer}</p></div><p class="feedback ${reply.good?'is-success':'is-retry'}" role="status">${reply.good?'Ответ помог прояснить вопрос.':'Нужно уточнить ответ.'} ${tip}</p><div class="actions">${action(index===4?'Посмотреть разбор':'Продолжить диалог','next')}</div>`
    : `<div class="options">${options.map((option,i)=>action(option,'reply',i,'option')).join('')}</div>${hint?`<p class="feedback" role="status">Подсказка · ${tip}</p>`:action('Взять подсказку','hint','','quiet chat-hint')}`}
    </section></div>`;
}

Game.init({restart,onAction(name,value){
  if (name==='customer') customer=cases[Number(value)];
  if (name==='hint') hint=true;
  if (name==='reply' && !reply) {
    const current=stage();
    const good=Number(value)===index%2;
    trust=clamp(trust+(good?13:-10));
    interest=clamp(interest+(good?12:-7));
    reply={stage:current,good,trust,points:good?20:0,topic:current[3],feedback:current[4],answer:current[good?1:2]};
    records.push(reply);
  }
  if (name==='next' && reply) {
    if (index===4) finished=true;
    else index++;
    reply=null;
    hint=false;
  }
  render();
  if (name==='reply') root.querySelector('[data-action="next"]')?.focus();
  if (finished) root.querySelector('.reward .btn')?.focus();
}});
